const codes = `AD AE AF AG AL AM AO AR AT AU AZ BA BB BD BE BF BG BH BI BJ BN BO BR BS BT BW BY BZ CA CD CF CG CH CI CL CM CN CO CR CU CV CY CZ DE DJ DK DM DO DZ EC EE EG ER ES ET FI FJ FM FR GA GB GD GE GH GM GN GQ GR GT GW GY HK HN HR HT HU ID IE IL IN IQ IR IS IT JM JO JP KE KG KH KI KM KN KP KR KW KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MG MH MK ML MM MN MR MT MU MV MW MX MY MZ NA NE NG NI NL NO NP NR NZ OM PA PE PG PH PK PL PS PT PW PY QA RO RS RU RW SA SB SC SD SE SG SI SK SL SM SN SO SR SS ST SV SY SZ TD TG TH TJ TL TM TN TO TR TT TV TW TZ UA UG US UY UZ VA VC VE VN VU WS YE ZA ZM ZW`.split(/\s+/);
const dn = new Intl.DisplayNames(['en'], { type: 'region' });
const rows = codes.map(c => ({ code: c, name: dn.of(c) })).filter(r => r.name && r.name !== r.code);
rows.sort((a,b)=>a.name.localeCompare(b.name));
// India first, then alphabetical.
const indiaIdx = rows.findIndex(r=>r.code==='IN');
const india = rows.splice(indiaIdx,1)[0];
const out = `// AUTO-GENERATED by scripts/gen-countries.ts — do not edit by hand.
// Source: ISO 3166-1 alpha-2 codes, display names from the Node Intl.DisplayNames API.
// India is pinned first because it is the home market and the R4 exception.

export interface Country {
  /** ISO 3166-1 alpha-2 */
  code: string;
  name: string;
}

export const INDIA = ${JSON.stringify(india)} as const;

export const COUNTRIES: readonly Country[] = [
${[india, ...rows].map(r=>`  { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)} },`).join('\n')}
];

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));
const BY_NAME = new Map(COUNTRIES.map((c) => [c.name.toLowerCase(), c]));

export function findCountry(input: string | null | undefined): Country | null {
  if (!input) return null;
  const needle = input.trim();
  if (!needle) return null;
  return BY_CODE.get(needle.toUpperCase()) ?? BY_NAME.get(needle.toLowerCase()) ?? null;
}

export function isIndia(input: string | null | undefined): boolean {
  return findCountry(input)?.code === 'IN';
}

export function countryNames(): readonly string[] {
  return COUNTRIES.map((c) => c.name);
}
`;
process.stdout.write(out);
